class Car:
    def __init__(self, brand, model):
        self.brand = brand
        self.model = model


car1 = Car("mersedes", "gelik")
car2 = Car("chevrolet", "tracker")


print("Car 1 Brand:", car1.brand)
print("Car 1 Model:", car1.model)

print("Car 2 Brand:", car2.brand)
print("Car 2 Model:", car2.model)

